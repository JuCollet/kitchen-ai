-- Sign-in: Google identities and passkeys.
--
-- An account is created at the first Google sign-in. The person can then add passkeys to sign in
-- without Google (Spring Security only registers passkeys for an authenticated user).

-- Google account linked to a Kitchen account. The subject ("sub" claim) is Google's stable id;
-- the email may change on Google's side.
create table federated_identity (
    provider   varchar(20)  not null check (provider in ('google')),
    subject    varchar(255) not null,
    user_id    uuid         not null references app_user (id) on delete cascade,
    created_at timestamptz  not null default now(),
    primary key (provider, subject)
);

create index federated_identity_user_idx on federated_identity (user_id);

-- Passkeys: schema expected by Spring Security's JDBC repositories, copied from
-- spring-security-web 7.1.2 (user-entities-schema.sql, user-credentials-schema-postgres.sql).
-- Column names and types must stay as Spring Security reads and writes them, which is why
-- these two tables do not follow our conventions (varchar ids, timestamp without time zone).

-- WebAuthn user entity. "name" is the Kitchen user id (the authenticated principal name), and
-- "id" is a random user handle generated by Spring Security.
create table user_entities (
    id           varchar(1000) not null,
    name         varchar(100)  not null unique,
    display_name varchar(200),
    -- Our addition: ties the entity to the Kitchen account, so that deleting the account deletes
    -- its passkeys. Computed from "name", so Spring Security's inserts keep working unchanged.
    app_user_id  uuid          generated always as (name::uuid) stored not null
                               references app_user (id) on delete cascade,
    primary key (id)
);

create table user_credentials (
    credential_id                varchar(1000) not null,
    user_entity_user_id          varchar(1000) not null
                                               references user_entities (id) on delete cascade,
    public_key                   bytea         not null,
    signature_count              bigint,
    uv_initialized               boolean,
    backup_eligible              boolean       not null,
    authenticator_transports     varchar(1000),
    public_key_credential_type   varchar(100),
    backup_state                 boolean       not null,
    attestation_object           bytea,
    attestation_client_data_json bytea,
    created                      timestamp,
    last_used                    timestamp,
    label                        varchar(1000) not null,
    primary key (credential_id)
);

create index user_credentials_user_entity_idx on user_credentials (user_entity_user_id);
